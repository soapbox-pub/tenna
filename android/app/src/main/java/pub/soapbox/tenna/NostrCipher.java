package pub.soapbox.tenna;

import java.nio.charset.StandardCharsets;
import java.security.SecureRandom;
import java.util.Arrays;

import javax.crypto.Cipher;
import javax.crypto.Mac;
import javax.crypto.spec.IvParameterSpec;
import javax.crypto.spec.SecretKeySpec;

/**
 * The symmetric half of the encryption NIPs: NIP-44 v2 under a conversation
 * key, and NIP-04 under a raw shared secret. {@link NostrCrypto} supplies both
 * keys; nothing here touches the curve.
 *
 * <p>SHA-256, HMAC-SHA256 and AES-CBC come from the platform JCE.
 * ChaCha20 does not — the JCE gained it in API 28 and {@code minSdk} here is
 * 24 — so the RFC 8439 keystream is spelled out below. That, HKDF-Expand and
 * the NIP-44 framing are ported verbatim from Armada's {@code ConcordCrypto},
 * where they have been pinned since 2026 against payloads generated by
 * nostr-tools and {@code @noble/ciphers}; {@code NostrCipherTest} carries the
 * same vectors.
 *
 * <p>NIP-44 v2 wire format (after base64 decode):
 * {@code [version=2 (1)] [nonce (32)] [ciphertext (n)] [mac (32)]}.
 * Message keys are {@code HKDF-Expand(SHA-256, conversationKey, nonce, 76)} →
 * {@code chacha_key[0:32]}, {@code chacha_nonce[32:44]}, {@code hmac_key[44:76]}.
 * The MAC is {@code HMAC-SHA256(hmac_key, nonce || ciphertext)}.
 *
 * <p>Every method is best-effort: {@code null} on malformed input, a MAC that
 * doesn't check out, or a decode failure. None of them throw, and none of them
 * say which of those it was — a padding oracle is not a thing to hand a site.
 */
final class NostrCipher {

    private NostrCipher() {}

    private static final SecureRandom RANDOM = new SecureRandom();

    // ── NIP-44 v2 ────────────────────────────────────────────────────────────

    /**
     * Decrypt a NIP-44 v2 base64 payload under a raw 32-byte conversation key.
     * Returns the plaintext, or {@code null} on any malformed input / MAC
     * mismatch / decode failure.
     */
    static String decrypt44(byte[] conversationKey, String payloadB64) {
        try {
            if (payloadB64 == null || payloadB64.isEmpty() || payloadB64.charAt(0) == '#') return null;
            return decrypt44Bytes(conversationKey,
                    android.util.Base64.decode(payloadB64, android.util.Base64.DEFAULT));
        } catch (Exception e) {
            return null;
        }
    }

    /**
     * The byte-level decrypt core, below the base64.
     *
     * <p>Separate from {@link #decrypt44} only because {@code
     * android.util.Base64} is a stub in a JVM unit test, and the MAC check
     * below is the part that most needs testing.
     */
    static String decrypt44Bytes(byte[] conversationKey, byte[] data) {
        try {
            if (conversationKey == null || conversationKey.length != 32) return null;
            if (data == null) return null;
            // version(1) + nonce(32) + ciphertext(>= 34) + mac(32) = 99 minimum.
            if (data.length < 99) return null;
            if ((data[0] & 0xff) != 2) return null;

            byte[] nonce = Arrays.copyOfRange(data, 1, 33);
            byte[] ciphertext = Arrays.copyOfRange(data, 33, data.length - 32);
            byte[] mac = Arrays.copyOfRange(data, data.length - 32, data.length);

            byte[] keys = hkdfExpand(conversationKey, nonce, 76);
            byte[] chachaKey = Arrays.copyOfRange(keys, 0, 32);
            byte[] chachaNonce = Arrays.copyOfRange(keys, 32, 44);
            byte[] hmacKey = Arrays.copyOfRange(keys, 44, 76);

            byte[] aadMsg = new byte[nonce.length + ciphertext.length];
            System.arraycopy(nonce, 0, aadMsg, 0, nonce.length);
            System.arraycopy(ciphertext, 0, aadMsg, nonce.length, ciphertext.length);
            byte[] expectedMac = hmacSha256(hmacKey, aadMsg);
            if (!constantTimeEquals(expectedMac, mac)) return null;

            byte[] padded = chacha20(chachaKey, chachaNonce, ciphertext);
            return unpad(padded);
        } catch (Exception e) {
            return null;
        }
    }

    /**
     * Encrypt a plaintext to a NIP-44 v2 base64 payload under a raw 32-byte
     * conversation key — the inverse of {@link #decrypt44}. Null on failure.
     */
    static String encrypt44(byte[] conversationKey, String plaintext) {
        byte[] nonce = new byte[32];
        RANDOM.nextBytes(nonce);
        byte[] payload = encrypt44Bytes(conversationKey, plaintext, nonce);
        return payload != null
                ? android.util.Base64.encodeToString(payload, android.util.Base64.NO_WRAP)
                : null;
    }

    /** The byte-level encrypt core (fixed nonce injectable for the unit test). */
    static byte[] encrypt44Bytes(byte[] conversationKey, String plaintext, byte[] nonce) {
        try {
            if (conversationKey == null || conversationKey.length != 32) return null;
            byte[] unpadded = plaintext.getBytes(StandardCharsets.UTF_8);
            if (unpadded.length < 1) return null;

            byte[] keys = hkdfExpand(conversationKey, nonce, 76);
            byte[] chachaKey = Arrays.copyOfRange(keys, 0, 32);
            byte[] chachaNonce = Arrays.copyOfRange(keys, 32, 44);
            byte[] hmacKey = Arrays.copyOfRange(keys, 44, 76);

            byte[] padded = pad(unpadded);

            byte[] ciphertext = chacha20(chachaKey, chachaNonce, padded);
            byte[] macMsg = new byte[nonce.length + ciphertext.length];
            System.arraycopy(nonce, 0, macMsg, 0, nonce.length);
            System.arraycopy(ciphertext, 0, macMsg, nonce.length, ciphertext.length);
            byte[] mac = hmacSha256(hmacKey, macMsg);

            byte[] payload = new byte[1 + 32 + ciphertext.length + 32];
            payload[0] = 2;
            System.arraycopy(nonce, 0, payload, 1, 32);
            System.arraycopy(ciphertext, 0, payload, 33, ciphertext.length);
            System.arraycopy(mac, 0, payload, 33 + ciphertext.length, 32);
            return payload;
        } catch (Exception e) {
            return null;
        }
    }

    // ── NIP-04 ───────────────────────────────────────────────────────────────

    /**
     * Encrypt to the legacy NIP-04 form: AES-256-CBC under the raw ECDH shared
     * secret, with a random IV, rendered {@code base64(ct)?iv=base64(iv)}.
     *
     * <p>NIP-04 is deprecated and leaks its plaintext length, but sites still
     * ask for it and the web layer has always answered, so the native signer
     * has to as well or moving the key would cost a capability.
     */
    static String encrypt04(byte[] sharedSecret, String plaintext) {
        try {
            byte[] iv = new byte[16];
            RANDOM.nextBytes(iv);
            byte[] ct = encrypt04Bytes(sharedSecret, plaintext, iv);
            if (ct == null) return null;
            return android.util.Base64.encodeToString(ct, android.util.Base64.NO_WRAP)
                    + "?iv=" + android.util.Base64.encodeToString(iv, android.util.Base64.NO_WRAP);
        } catch (Exception e) {
            return null;
        }
    }

    /** Decrypt the NIP-04 form. Null on anything malformed. */
    static String decrypt04(byte[] sharedSecret, String payload) {
        try {
            if (payload == null) return null;
            int at = payload.indexOf("?iv=");
            if (at < 0) return null;
            byte[] ct = android.util.Base64.decode(payload.substring(0, at), android.util.Base64.DEFAULT);
            byte[] iv = android.util.Base64.decode(payload.substring(at + 4), android.util.Base64.DEFAULT);
            return decrypt04Bytes(sharedSecret, ct, iv);
        } catch (Exception e) {
            return null;
        }
    }

    /** The AES-CBC core of {@link #encrypt04}, below the base64. */
    static byte[] encrypt04Bytes(byte[] sharedSecret, String plaintext, byte[] iv) {
        try {
            if (sharedSecret == null || sharedSecret.length != 32) return null;
            if (iv == null || iv.length != 16) return null;
            Cipher cipher = Cipher.getInstance("AES/CBC/PKCS5Padding");
            cipher.init(Cipher.ENCRYPT_MODE, new SecretKeySpec(sharedSecret, "AES"), new IvParameterSpec(iv));
            return cipher.doFinal(plaintext.getBytes(StandardCharsets.UTF_8));
        } catch (Exception e) {
            return null;
        }
    }

    /** The AES-CBC core of {@link #decrypt04}, below the base64. */
    static String decrypt04Bytes(byte[] sharedSecret, byte[] ciphertext, byte[] iv) {
        try {
            if (sharedSecret == null || sharedSecret.length != 32) return null;
            if (iv == null || iv.length != 16) return null;
            Cipher cipher = Cipher.getInstance("AES/CBC/PKCS5Padding");
            cipher.init(Cipher.DECRYPT_MODE, new SecretKeySpec(sharedSecret, "AES"), new IvParameterSpec(iv));
            return new String(cipher.doFinal(ciphertext), StandardCharsets.UTF_8);
        } catch (Exception e) {
            return null;
        }
    }

    // ── NIP-44 padding ──────────────────────────────────────────────────────

    /** NIP-44 padded length: 32-byte floor, then power-of-two-derived chunks. */
    private static int calcPaddedLen(int unpaddedLen) {
        if (unpaddedLen <= 32) return 32;
        int nextPower = Integer.highestOneBit(unpaddedLen - 1) << 1;
        int chunk = nextPower <= 256 ? 32 : nextPower / 8;
        return chunk * ((unpaddedLen - 1) / chunk + 1);
    }

    /** Plaintexts this long or longer take the extended u32 length prefix. */
    private static final int EXTENDED_PREFIX_THRESHOLD = 65536;

    /**
     * Add NIP-44 padding: {@code [u16-BE len][plaintext][zeros]}, or
     * {@code [0x0000][u32-BE len][plaintext][zeros]} from 64 KiB up. Without
     * the extended form a bunker cannot answer with a large signed event, and
     * the client waits out its timeout for a reply that never comes.
     */
    private static byte[] pad(byte[] unpadded) {
        int len = unpadded.length;
        int prefixLen = len >= EXTENDED_PREFIX_THRESHOLD ? 6 : 2;
        byte[] padded = new byte[prefixLen + calcPaddedLen(len)];
        if (prefixLen == 6) {
            padded[2] = (byte) (len >>> 24);
            padded[3] = (byte) (len >>> 16);
            padded[4] = (byte) (len >>> 8);
            padded[5] = (byte) len;
        } else {
            padded[0] = (byte) (len >>> 8);
            padded[1] = (byte) len;
        }
        System.arraycopy(unpadded, 0, padded, prefixLen, len);
        return padded;
    }

    /** Strip NIP-44 padding: [u16-BE len][plaintext][zeros] (extended u32 form for >= 65536). */
    private static String unpad(byte[] padded) {
        if (padded.length < 2) return null;
        int firstTwo = ((padded[0] & 0xff) << 8) | (padded[1] & 0xff);
        int unpaddedLen;
        int prefixLen;
        if (firstTwo == 0) {
            if (padded.length < 6) return null;
            unpaddedLen = ((padded[2] & 0xff) << 24) | ((padded[3] & 0xff) << 16)
                    | ((padded[4] & 0xff) << 8) | (padded[5] & 0xff);
            if (unpaddedLen < EXTENDED_PREFIX_THRESHOLD) return null;
            prefixLen = 6;
        } else {
            unpaddedLen = firstTwo;
            prefixLen = 2;
        }
        if (unpaddedLen < 1) return null;
        if ((long) prefixLen + calcPaddedLen(unpaddedLen) != padded.length) return null;
        return new String(padded, prefixLen, unpaddedLen, StandardCharsets.UTF_8);
    }

    // ── HKDF (expand only) ────────────────────────────────────────────────────

    /** RFC 5869 HKDF-Expand with SHA-256. {@code prk} is the conversation key. */
    private static byte[] hkdfExpand(byte[] prk, byte[] info, int length) throws Exception {
        int hashLen = 32;
        int n = (int) Math.ceil((double) length / hashLen);
        byte[] okm = new byte[n * hashLen];
        byte[] t = new byte[0];
        int pos = 0;
        for (int i = 1; i <= n; i++) {
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(prk, "HmacSHA256"));
            mac.update(t);
            mac.update(info);
            mac.update((byte) i);
            t = mac.doFinal();
            System.arraycopy(t, 0, okm, pos, hashLen);
            pos += hashLen;
        }
        return Arrays.copyOfRange(okm, 0, length);
    }

    private static byte[] hmacSha256(byte[] key, byte[] message) throws Exception {
        Mac mac = Mac.getInstance("HmacSHA256");
        mac.init(new SecretKeySpec(key, "HmacSHA256"));
        return mac.doFinal(message);
    }

    private static boolean constantTimeEquals(byte[] a, byte[] b) {
        if (a == null || b == null || a.length != b.length) return false;
        int diff = 0;
        for (int i = 0; i < a.length; i++) diff |= a[i] ^ b[i];
        return diff == 0;
    }

    // ── ChaCha20 (RFC 8439, 12-byte nonce, counter from 0) ────────────────────

    /**
     * ChaCha20 keystream XOR (IETF variant): 256-bit key, 96-bit nonce, 32-bit
     * block counter starting at 0 — matching @noble/ciphers' {@code chacha20}
     * used by nostr-tools' NIP-44. Pure Java so it works below API 28, where
     * the JCE {@code "ChaCha20"} cipher isn't available; minSdk is 24.
     */
    static byte[] chacha20(byte[] key, byte[] nonce, byte[] input) {
        int[] state = new int[16];
        state[0] = 0x61707865;
        state[1] = 0x3320646e;
        state[2] = 0x79622d32;
        state[3] = 0x6b206574;
        for (int i = 0; i < 8; i++) state[4 + i] = leInt(key, i * 4);
        state[12] = 0; // counter
        state[13] = leInt(nonce, 0);
        state[14] = leInt(nonce, 4);
        state[15] = leInt(nonce, 8);

        byte[] out = new byte[input.length];
        byte[] block = new byte[64];
        int offset = 0;
        while (offset < input.length) {
            chachaBlock(state, block);
            int n = Math.min(64, input.length - offset);
            for (int i = 0; i < n; i++) {
                out[offset + i] = (byte) (input[offset + i] ^ block[i]);
            }
            offset += n;
            state[12]++; // increment 32-bit counter
        }
        return out;
    }

    private static void chachaBlock(int[] state, byte[] out) {
        int[] x = Arrays.copyOf(state, 16);
        for (int i = 0; i < 10; i++) {
            // column rounds
            quarterRound(x, 0, 4, 8, 12);
            quarterRound(x, 1, 5, 9, 13);
            quarterRound(x, 2, 6, 10, 14);
            quarterRound(x, 3, 7, 11, 15);
            // diagonal rounds
            quarterRound(x, 0, 5, 10, 15);
            quarterRound(x, 1, 6, 11, 12);
            quarterRound(x, 2, 7, 8, 13);
            quarterRound(x, 3, 4, 9, 14);
        }
        for (int i = 0; i < 16; i++) {
            int v = x[i] + state[i];
            out[i * 4] = (byte) v;
            out[i * 4 + 1] = (byte) (v >>> 8);
            out[i * 4 + 2] = (byte) (v >>> 16);
            out[i * 4 + 3] = (byte) (v >>> 24);
        }
    }

    private static void quarterRound(int[] x, int a, int b, int c, int d) {
        x[a] += x[b]; x[d] ^= x[a]; x[d] = Integer.rotateLeft(x[d], 16);
        x[c] += x[d]; x[b] ^= x[c]; x[b] = Integer.rotateLeft(x[b], 12);
        x[a] += x[b]; x[d] ^= x[a]; x[d] = Integer.rotateLeft(x[d], 8);
        x[c] += x[d]; x[b] ^= x[c]; x[b] = Integer.rotateLeft(x[b], 7);
    }

    private static int leInt(byte[] b, int off) {
        return (b[off] & 0xff)
                | ((b[off + 1] & 0xff) << 8)
                | ((b[off + 2] & 0xff) << 16)
                | ((b[off + 3] & 0xff) << 24);
    }

    // ── Hex ───────────────────────────────────────────────────────────────────

    /** Decode a hex string to bytes; returns {@code null} on malformed input. */
    static byte[] hexToBytes(String hex) {
        if (hex == null) return null;
        int len = hex.length();
        if (len % 2 != 0) return null;
        byte[] out = new byte[len / 2];
        for (int i = 0; i < len; i += 2) {
            int hi = Character.digit(hex.charAt(i), 16);
            int lo = Character.digit(hex.charAt(i + 1), 16);
            if (hi < 0 || lo < 0) return null;
            out[i / 2] = (byte) ((hi << 4) | lo);
        }
        return out;
    }
}
